// Request Context (for logging and tracking)
export interface RequestContext {
  requestId: string;
  userId?: string;
  sessionId?: string;
  userAgent?: string;
  ipAddress?: string;
  timestamp: string;
  endpoint: string;
}

// YouTube Transcript API Options
export interface TranscriptFetchOptions {
  languages?: string[]; // Priority order of languages to fetch
  includeAutoGenerated?: boolean; // Whether to include auto-generated transcripts
  fallbackToAnyLanguage?: boolean; // Fallback if preferred language not available
}

// Chapter Generation AI Model Configuration
export interface AIModelConfig {
  model: string; // e.g., 'gpt-4', 'claude-3'
  temperature?: number;
  maxTokens?: number;
  systemPrompt?: string;
  userPromptTemplate?: string;
}

// Webhook Types (for async processing)
export interface WebhookConfig {
  url: string;
  secret?: string;
  events: WebhookEvent[];
}

export enum WebhookEvent {
  TRANSCRIPT_READY = 'transcript.ready',
  CHAPTERS_GENERATED = 'chapters.generated',
  EXPORT_READY = 'export.ready',
  PROCESSING_FAILED = 'processing.failed'
}

export interface WebhookPayload {
  event: WebhookEvent;
  data: any;
  timestamp: string;
  requestId: string;
}

// Analytics and Metrics Types
