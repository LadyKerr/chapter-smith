// API Types for Chapter Smith Backend
// Comprehensive TypeScript interfaces for all API endpoints

// YouTube API Related Types
export interface YouTubeVideoInfo {
  id: string;
  title: string;
  description: string;
  duration: string;
  channelTitle: string;
  publishedAt: string;
  thumbnailUrl: string;
  viewCount?: string;
  likeCount?: string;
  url: string;
}

export interface YouTubeTranscriptSegment {
  text: string;
  start: number;
  duration: number;
}

export interface YouTubeTranscriptResponse {
  videoId: string;
  title: string;
  duration: number;
  segments: YouTubeTranscriptSegment[];
  language?: string;
  isAutoGenerated: boolean;
}

// Chapter Generation Types
export interface ChapterGenerationRequest {
  videoId?: string;
  url?: string;
  transcript?: YouTubeTranscriptSegment[];
  options?: {
    minChapterLength?: number; // in seconds, default 60
    maxChapters?: number; // default 20
    includeDescriptions?: boolean; // default true
    language?: string; // default 'en'
  };
}

export interface GeneratedChapter {
  id: string;
  timestamp: string;
  title: string;
  description?: string;
  startTime: number; // in seconds
  endTime?: number;
  confidence?: number; // 0-1 confidence score
  keywords?: string[];
}

export interface ChapterGenerationResponse {
  videoInfo: YouTubeVideoInfo;
  chapters: GeneratedChapter[];
  metadata: {
    totalChapters: number;
    averageChapterLength: number;
    processingTimeMs: number;
    model: string;
    language: string;
  };
}

// Export Types
export interface ExportRequest {
  chapters: GeneratedChapter[];
  format: ExportFormat;
  videoInfo?: YouTubeVideoInfo;
  options?: ExportOptions;
}

export interface ExportOptions {
  includeTimestamps?: boolean;
  includeDescriptions?: boolean;
  includeVideoInfo?: boolean;
  customTemplate?: string;
  timezone?: string;
}

export type ExportFormat = 
  | 'youtube' 
  | 'text' 
  | 'json' 
  | 'csv' 
  | 'srt' 
  | 'vtt' 
  | 'xml' 
  | 'markdown';

export interface ExportResponse {
  content: string;
  filename: string;
  mimeType: string;
  size: number;
  downloadUrl?: string;
  expiresAt?: string;
}

// API Response Wrappers
export interface APISuccessResponse<T> {
  success: true;
  data: T;
  message?: string;
  timestamp: string;
  version: string;
}

export interface APIErrorResponse {
  success: false;
  error: {
    code: string;
    message: string;
    details?: any;
    stack?: string; // Only in development
  };
  timestamp: string;
  version: string;
}

export type APIResponse<T> = APISuccessResponse<T> | APIErrorResponse;

// Validation Types
export interface ValidationResult {
  isValid: boolean;
  errors: ValidationError[];
  warnings: ValidationWarning[];
}

export interface ValidationError {
  field: string;
  code: string;
  message: string;
  value?: any;
}

export interface ValidationWarning {
  field: string;
  code: string;
  message: string;
  suggestion?: string;
}

// Rate Limiting Types
export interface RateLimitInfo {
  limit: number;
  remaining: number;
  resetTime: number;
  retryAfter?: number;
}

// YouTube API Quota Types
export interface YouTubeQuotaInfo {
  dailyLimit: number;
  used: number;
  remaining: number;
  resetTime: number;
}

