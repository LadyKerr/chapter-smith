/**
 * YouTube Transcript API Endpoint
 * Fetches transcript data from YouTube videos
 * 
 * POST /api/youtube/transcript
 * 
 * Body: {
 *   url?: string,           // YouTube video URL
 *   videoId?: string,       // YouTube video ID
 *   options?: {
 *     languages?: string[],          // Language preference order
 *     includeAutoGenerated?: boolean, // Include auto-generated transcripts
 *     fallbackToAnyLanguage?: boolean // Fallback if preferred lang unavailable
 *   }
 * }
 */
export async function POST(request: NextRequest): Promise<NextResponse> {
  const startTime = Date.now();
  const requestId = generateRequestId();
  let body: TranscriptRequest;
  let videoId: string | undefined;

  // Validate environment variables first
  const environmentValidation = validateEnvironment();
  if (!environmentValidation.isValid) {
    return createErrorResponse(
      APIErrorCode.CONFIGURATION_ERROR,
      'Server configuration error',
      {
        missing: environmentValidation.missing,
        suggestions: [
          'Set YOUTUBE_API_KEY environment variable',
          'Ensure YouTube Data API v3 is enabled',
          'Check API key permissions and quotas'
        ]
      },
      500
    );
  }

  try {
    // Check authentication first
    const authenticated = await isAuthenticated(request);
    if (!authenticated) {
      return createErrorResponse(
        APIErrorCode.UNAUTHORIZED,
        'Authentication required. Please provide a valid API key via x-api-key header.',
        null,
        401
      );
    }

    // Parse and validate request body
    body = await request.json();
    const validation = validateTranscriptRequest(body);

    if (!validation.isValid) {
      return createErrorResponse(
        APIErrorCode.INVALID_FIELD_TYPE,
        'Validation failed',
        validation.errors,
        400
      );
    }

    // Extract video ID from URL or use provided videoId
    videoId = body.videoId || extractVideoIdFromUrl(body.url!);
    if (!videoId) {
      return createErrorResponse(
        APIErrorCode.INVALID_VIDEO_ID,
        'Invalid YouTube URL or video ID',
        null,
        400
      );
    }

    // Check rate limiting
    const rateLimitCheck = await checkRateLimit(request);
    if (!rateLimitCheck.allowed) {
      return createErrorResponse(
        APIErrorCode.RATE_LIMIT_EXCEEDED,
        'Rate limit exceeded',
        { retryAfter: rateLimitCheck.retryAfter },
        429
      );
    }

    // Check YouTube API quota
    const quotaCheck = await checkYouTubeQuota();
    if (!quotaCheck.available) {
      return createErrorResponse(
        APIErrorCode.YOUTUBE_QUOTA_EXCEEDED,
        'YouTube API quota exceeded',
        { resetTime: quotaCheck.resetTime },
        503
      );
    }

    // Fetch video information first
    const videoInfo = await fetchVideoInfo(videoId);
    if (!videoInfo) {
      return createErrorResponse(
        APIErrorCode.VIDEO_NOT_FOUND,
        'Video not found or is private',
        null,
        404
      );
    }

    // Attempt to fetch transcript
    const transcriptData = await fetchTranscript(videoId, body.options);
    
    if (!transcriptData) {
      return createErrorResponse(
        APIErrorCode.NO_TRANSCRIPT_AVAILABLE,
        'No transcript available for this video',
        { 
          videoId,
          suggestions: [
            'Try uploading an SRT file manually',
            'Check if the video has captions enabled',
            'Contact the video creator to enable captions'
          ]
        },
        404
      );
    }

    // Prepare successful response
    const response: YouTubeTranscriptResponse = {
      videoId,
      title: videoInfo.title,
      duration: parseDurationToSeconds(videoInfo.duration),
      segments: transcriptData.segments,
      language: transcriptData.language,
      isAutoGenerated: transcriptData.isAutoGenerated
    };

    // Log success metrics
    await logProcessingMetrics({
      requestId,
      videoId,
      transcriptFetchTimeMs: Date.now() - startTime,
      transcriptLength: transcriptData.segments.length,
      success: true
    });

    return createSuccessResponse(response);

  } catch (error) {
    console.error('Transcript fetch error:', error);
    
    // Log error metrics
    await logProcessingMetrics({
      requestId,
      videoId: videoId || 'unknown',
      transcriptFetchTimeMs: Date.now() - startTime,
      success: false,
      error: error instanceof Error ? error.message : 'Unknown error'
    });

    if (error instanceof YouTubeAPIError) {
      return createErrorResponse(
        error.code,
        error.message,
        error.details,
        error.statusCode
      );
    }

    return createErrorResponse(
      APIErrorCode.INTERNAL_SERVER_ERROR,
      'Failed to fetch transcript',
      process.env.NODE_ENV === 'development' ? { stack: error } : null,
      500
    );
  }
}

/**
 * Validate environment configuration
 */
function validateEnvironment(): { isValid: boolean; missing: string[] } {
  const missing: string[] = [];
  
  if (!process.env.YOUTUBE_API_KEY) {
    missing.push('YOUTUBE_API_KEY');
  }
  
  // Optional: validate API key format (should be ~39 characters starting with AIza)
  if (process.env.YOUTUBE_API_KEY && !process.env.YOUTUBE_API_KEY.startsWith('AIza')) {
    console.warn('YouTube API key format appears invalid - should start with "AIza"');
  }
  
  return {
    isValid: missing.length === 0,
    missing
  };
}

/**
 * Validate transcript request body
 */
function validateTranscriptRequest(body: TranscriptRequest): ValidationResult {
  const errors = [];
  const warnings = [];

  // Must have either URL or videoId
  if (!body.url && !body.videoId) {
    errors.push({
      field: 'url_or_videoId',
      code: 'MISSING_REQUIRED',
      message: 'Either URL or videoId is required',
      value: null
    });
  }

  // Validate URL format if provided
  if (body.url && !isValidYouTubeUrl(body.url)) {
    errors.push({
      field: 'url',
      code: 'INVALID_FORMAT',
      message: 'Invalid YouTube URL format',
      value: body.url
    });
  }

  // Validate videoId format if provided
  if (body.videoId && !isValidVideoId(body.videoId)) {
    errors.push({
      field: 'videoId',
      code: 'INVALID_FORMAT',
      message: 'Invalid YouTube video ID format',
      value: body.videoId
    });
  }

  // Validate options if provided
  if (body.options) {
    if (body.options.languages && !Array.isArray(body.options.languages)) {
      errors.push({
        field: 'options.languages',
        code: 'INVALID_TYPE',
        message: 'Languages must be an array of strings',
        value: body.options.languages
      });
    }

    if (body.options.languages && body.options.languages.length > 10) {
      warnings.push({
        field: 'options.languages',
        code: 'TOO_MANY_LANGUAGES',
        message: 'Maximum 10 languages supported',
        suggestion: 'Limit to top 3-5 preferred languages for better performance'
      });
    }
  }

  return {
    isValid: errors.length === 0,
    errors,
    warnings
  };
}

/**
 * Extract YouTube video ID from various URL formats
 */
function extractVideoIdFromUrl(url: string): string | null {
  const patterns = [
    /(?:youtube\.com\/watch\?v=|youtu\.be\/|youtube\.com\/embed\/)([a-zA-Z0-9_-]{11})/,
    /youtube\.com\/v\/([a-zA-Z0-9_-]{11})/,
    /youtube\.com\/watch\?.*v=([a-zA-Z0-9_-]{11})/
  ];

  for (const pattern of patterns) {
    const match = url.match(pattern);
    if (match) return match[1];
  }

  return null;
}

/**
 * Validate YouTube URL format
 */
function isValidYouTubeUrl(url: string): boolean {
  const youtubeRegex = /^(https?:\/\/)?(www\.)?(youtube\.com|youtu\.be)\/.+/;
  return youtubeRegex.test(url);
}

/**
 * Validate YouTube video ID format
 */
function isValidVideoId(videoId: string): boolean {
  return /^[a-zA-Z0-9_-]{11}$/.test(videoId);
}

/**
 * Fetch video information from YouTube Data API v3
 */
async function fetchVideoInfo(videoId: string): Promise<YouTubeVideoInfo | null> {
  const apiKey = process.env.YOUTUBE_API_KEY;
  if (!apiKey) {
    throw new YouTubeAPIError(
      APIErrorCode.CONFIGURATION_ERROR,
      'YouTube API key not configured',
      null,
      500
    );
  }
  
  console.log(`Fetching video info for ID: ${videoId}`);

  const url = `https://www.googleapis.com/youtube/v3/videos?id=${videoId}&part=snippet,contentDetails,statistics&key=${apiKey}`;
  
  try {
    const response = await fetch(url, {
      headers: {
        'User-Agent': 'ChapterSmith/1.0'
      }
    });

    if (!response.ok) {
      const errorText = await response.text();
      console.error(`YouTube API error: ${response.status} - ${errorText}`);
      
      throw new YouTubeAPIError(
        APIErrorCode.EXTERNAL_SERVICE_ERROR,
        `YouTube API error: ${response.status}`,
        { 
          status: response.status, 
          statusText: response.statusText,
          errorBody: errorText,
          url: url
        },
        response.status
      );
    }

    const data = await response.json();
    
    if (!data.items || data.items.length === 0) {
      return null; // Video not found or private
    }

    const video = data.items[0];
    const snippet = video.snippet;
    const contentDetails = video.contentDetails;
    const statistics = video.statistics;

    return {
      id: videoId,
      title: snippet.title,
      description: snippet.description,
      duration: contentDetails.duration,
      channelTitle: snippet.channelTitle,
      publishedAt: snippet.publishedAt,
      thumbnailUrl: snippet.thumbnails?.maxresdefault?.url || snippet.thumbnails?.high?.url,
      viewCount: statistics?.viewCount,
      likeCount: statistics?.likeCount,
      url: `https://www.youtube.com/watch?v=${videoId}`
    };

  } catch (error) {
    if (error instanceof YouTubeAPIError) throw error;
    
    throw new YouTubeAPIError(
      APIErrorCode.EXTERNAL_SERVICE_ERROR,
      'Failed to fetch video information',
      { originalError: error instanceof Error ? error.message : 'Unknown error' },
      500
    );
  }
}

/**
 * Fetch transcript using youtube-transcript library
 */
async function fetchTranscript(
  videoId: string, 
  options?: TranscriptFetchOptions
): Promise<{ segments: YouTubeTranscriptSegment[]; language: string; isAutoGenerated: boolean } | null> {
  
  try {
    console.log(`Attempting to fetch transcript for video ID: ${videoId}`);
    
    // Try to import youtube-transcript dynamically
    let YoutubeTranscript;
    try {
      YoutubeTranscript = (await import('youtube-transcript')).YoutubeTranscript;
      console.log('youtube-transcript library imported successfully');
    } catch {
      console.warn('youtube-transcript not available, using fallback implementation');
      return await fetchTranscriptFallback(videoId, options);
    }

    // Fetch transcript using the library
    console.log(`Fetching transcript with language: ${options?.languages?.[0] || 'en'}`);
    const transcriptData = await YoutubeTranscript.fetchTranscript(videoId, {
      lang: options?.languages?.[0] || 'en',
      country: 'US'
    });
    
    console.log(`Transcript data received: ${transcriptData?.length || 0} segments`);

    if (!transcriptData || transcriptData.length === 0) {
      console.log('No transcript data from library, trying fallback...');
      return await fetchTranscriptFallback(videoId, options);
    }

    // Transform to our format
    const segments: YouTubeTranscriptSegment[] = transcriptData.map((item: { text: string; offset: number; duration: number }) => ({
      text: item.text,
      start: item.offset / 1000, // Convert milliseconds to seconds
      duration: item.duration / 1000 // Convert milliseconds to seconds
    }));

    return {
      segments,
      language: options?.languages?.[0] || 'en',
      isAutoGenerated: true // Library doesn't provide this info, assume true
    };

  } catch (error) {
    console.error('Transcript fetch failed with error:', error);
    console.error('Error details:', {
      name: error instanceof Error ? error.name : 'Unknown',
      message: error instanceof Error ? error.message : 'Unknown error',
      videoId
    });
    
    // If main method fails, try fallback
    console.log('Attempting fallback transcript fetch...');
    return await fetchTranscriptFallback(videoId, options);
  }
}

