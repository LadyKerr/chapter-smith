/**
 * YouTube Transcript API Endpoint
 * Fetches transcript data from YouTube videos
 * 
 * POST /api/youtube/transcript
 * 
 * Body: {
 *   url?: string,           // YouTube video URL
 *   videoId?: string,       // YouTube video ID
 *   options?: {
 *     languages?: string[],          // Language preference order
 *     includeAutoGenerated?: boolean, // Include auto-generated transcripts
 *     fallbackToAnyLanguage?: boolean // Fallback if preferred lang unavailable
 *   }
 * }
 */
export async function POST(request: NextRequest): Promise<NextResponse> {
  const startTime = Date.now();
  const requestId = generateRequestId();
  let body: TranscriptRequest;
  let videoId: string | undefined;

  // Note: We use Python script for transcript fetching, so YouTube API key is optional

  try {
    // Parse and validate request body
    body = await request.json();
    const validation = validateTranscriptRequest(body);
    
    if (!validation.isValid) {
      return createErrorResponse(
        APIErrorCode.INVALID_FIELD_TYPE,
        'Validation failed',
        validation.errors,
        400
      );
    }

    // Extract video ID from URL or use provided videoId
    videoId = body.videoId || extractVideoIdFromUrl(body.url!);
    if (!videoId) {
      return createErrorResponse(
        APIErrorCode.INVALID_VIDEO_ID,
        'Invalid YouTube URL or video ID',
        null,
        400
      );
    }

    // Check rate limiting
    const rateLimitCheck = await checkRateLimit(request);
    if (!rateLimitCheck.allowed) {
      return createErrorResponse(
        APIErrorCode.RATE_LIMIT_EXCEEDED,
        'Rate limit exceeded',
        { retryAfter: rateLimitCheck.retryAfter },
        429
      );
    }

    // Check YouTube API quota
    const quotaCheck = await checkYouTubeQuota();
    if (!quotaCheck.available) {
      return createErrorResponse(
        APIErrorCode.YOUTUBE_QUOTA_EXCEEDED,
        'YouTube API quota exceeded',
        { resetTime: quotaCheck.resetTime },
        503
      );
    }

    // Attempt to fetch transcript (this will also get basic video info)
    const transcriptData = await fetchTranscript(videoId, body.options);
    
    if (!transcriptData) {
      return createErrorResponse(
        APIErrorCode.NO_TRANSCRIPT_AVAILABLE,
        'No transcript available for this video',
        { 
          videoId,
          suggestions: [
            'Try uploading an SRT file manually',
            'Check if the video has captions enabled',
            'Contact the video creator to enable captions'
          ]
        },
        404
      );
    }

    // Prepare successful response
    const response: YouTubeTranscriptResponse = {
      videoId,
      title: transcriptData.title || `Video ${videoId}`,
      duration: transcriptData.duration || Math.max(...transcriptData.segments.map(s => s.start + s.duration)),
      segments: transcriptData.segments,
      language: transcriptData.language,
      isAutoGenerated: transcriptData.isAutoGenerated
    };

    // Log success metrics
    await logProcessingMetrics({
      requestId,
      videoId,
      transcriptFetchTimeMs: Date.now() - startTime,
      transcriptLength: transcriptData.segments.length,
      success: true
    });

    return createSuccessResponse(response);

  } catch (error) {
    console.error('Transcript fetch error:', error);
    
    // Log error metrics
    await logProcessingMetrics({
      requestId,
      videoId: videoId || 'unknown',
      transcriptFetchTimeMs: Date.now() - startTime,
      success: false,
      error: error instanceof Error ? error.message : 'Unknown error'
    });

    if (error instanceof YouTubeAPIError) {
      return createErrorResponse(
        error.code,
        error.message,
        error.details,
        error.statusCode
      );
    }

    return createErrorResponse(
      APIErrorCode.INTERNAL_SERVER_ERROR,
      'Failed to fetch transcript',
      process.env.NODE_ENV === 'development' ? { stack: error } : null,
      500
    );
  }
}

